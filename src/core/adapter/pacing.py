"""回复分条发送的节奏：模拟真人打字（QQ / WebUI 共用）。

一条回复可能分好几条（§18.3：先应一声、再答正文）。条与条之间停一下更像真人在敲，
但"固定停 0.6 秒"是匀速的——不管下一条是「嗯」还是两百字小作文，停一样久，还是机械。

真人打字有两个特征，这里都建模：

1. **字数越多，打得越久**：延迟 = 下一条的字符数 × 每字秒数。
   注意算的是**下一条**：停多久取决于"接下来要敲多少"，而不是刚敲完多少。
2. **每次快慢不一**：再叠一个 [0, JITTER_SEC] 的随机量。同样字数的两条，
   也不会停出一模一样的间隔。

字数按**字符数**算即可（中文一字一字符、英文一字母一字符）——这是观感问题，
不是精度问题，不必按词/字节去算（§19-5：够用即可，不猜）。

两个平台共用这一个函数：QQ 在 `_send_one` 之间 sleep、WebUI 在推帧之间 sleep，
所以"分条的节奏"只有一份定义，不会两边各写一套然后漂移。
"""

import random

#: 每个字符占用的"打字"时间（秒）。0.22 ≈ 每秒 4.5 字，接近真人用输入法的节奏。
PER_CHAR_SEC = 0.22

#: 抖动的上限（秒）：再叠一个 0~它 的随机量，避免每次都停得一模一样。
JITTER_SEC = 0.5

#: 单条停顿的下限（秒）：太短多条几乎同时到达，客户端可能合并/乱序，
#: 也和"真人打字"的观感对不上——再短也得让人看清这一条。
MIN_DELAY_SEC = 0.4

#: 单条停顿的上限（秒）：模型偶尔会吐一大段，按字数线性算会停到几十秒，
#: 那是卡死不是打字。封顶。
MAX_DELAY_SEC = 4.0


def typing_delay(text: str) -> float:
    """下一条消息之前该停多久（秒）。

    只用于**分条之间**——第一条不等待（前面模型自身的耗时已经在拖了，
    前端也已经有"塔利在想…"的占位在顶着）。
    """
    chars = len(text or "")
    delay = chars * PER_CHAR_SEC + random.uniform(0.0, JITTER_SEC)
    return max(MIN_DELAY_SEC, min(MAX_DELAY_SEC, delay))
